"""Writes polars/scribblings/data/nul-expected.rktd from Python polars.

Run from the repo root with Python polars 1.42.1:
    python3 -I scripts/nul-expected.py
"""

import pathlib

import polars as pl

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = ROOT / "polars" / "scribblings" / "data"
N = "a\0b"


def enc(v):
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "#t" if v else "#f"
    if isinstance(v, str):
        out = "".join(c if " " <= c <= "~" and c not in '"\\' else
                      ("\\" + c if c in '"\\' else f"\\u{ord(c):04x}")
                      for c in v)
        return f'"{out}"'
    if isinstance(v, (list, tuple)):
        return "(" + " ".join(enc(x) for x in v) + ")"
    raise TypeError(repr(v))


def strs(xs):
    return pl.Series("s", xs, dtype=pl.String)


VALUES = [
    ("lit", (N,), lambda v: pl.select(pl.lit(v).alias("v"))["v"]),
    ("fill-null", (["x", None], N),
     lambda xs, v: strs(xs).fill_null(v)),
    ("strip-chars", ([N, "c"], N),
     lambda xs, v: strs(xs).str.strip_chars(v)),
    ("replace-literal", (["xa\0by"], N, "Z"),
     lambda xs, v, by: strs(xs).str.replace(v, by, literal=True)),
    ("contains-literal", (["xa\0by", "xa"], N),
     lambda xs, v: strs(xs).str.contains(v, literal=True)),
    ("starts-with", ([N, "a"], "a\0"),
     lambda xs, v: strs(xs).str.starts_with(v)),
    ("eq", ([N, "a"], N), lambda xs, v: strs(xs) == v),
    ("ne", ([N, "a"], N), lambda xs, v: strs(xs) != v),
]


def row(name, args, f):
    got = f(*args).to_list()
    return "  (" + " ".join([name, *(enc(a) for a in args), enc(got)]) + ")"


def main():
    rows = [row(*v) for v in VALUES]
    text = (f";; Generated by scripts/nul-expected.py from Python polars {pl.__version__};"
            " do not edit.\n((values\n" + "\n".join(rows) + "))\n")
    (DATA / "nul-expected.rktd").write_text(text)


if __name__ == "__main__":
    main()

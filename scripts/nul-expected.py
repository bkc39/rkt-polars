"""Writes polars/scribblings/data/nul-expected.rktd from Python polars.

Run from the repo root with Python polars 1.42.1:
    python3 -I scripts/nul-expected.py

`str-contains` reads its pattern as a regex, so the contains rows are
Python's `literal=False`.
"""

import pathlib
import sys

import polars as pl

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from rktd import datum

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "polars" / "scribblings" / "data" / "nul-expected.rktd"
N = "a\0b"


def strs(xs):
    return pl.Series("s", xs, dtype=pl.String)


VALUES = [
    ("lit", (N,), lambda v: pl.select(pl.lit(v).alias("v"))["v"]),
    ("fill-null", (["x", None], N),
     lambda xs, v: strs(xs).fill_null(v)),
    ("strip-chars", ([N, "c"], N),
     lambda xs, v: strs(xs).str.strip_chars(v)),
    ("replace-literal", (["xa\0by"], N, "Z"),
     lambda xs, v, by: strs(xs).str.replace(v, by, literal=True)),
    ("contains", (["xa\0by", "xa"], N),
     lambda xs, v: strs(xs).str.contains(v, literal=False)),
    ("contains", (["xa.\0by", "xaZ\0by", "xa"], "a.\0b"),
     lambda xs, v: strs(xs).str.contains(v, literal=False)),
    ("starts-with", ([N, "a"], "a\0"),
     lambda xs, v: strs(xs).str.starts_with(v)),
    ("eq", ([N, "a"], N), lambda xs, v: strs(xs) == v),
    ("ne", ([N, "a"], N), lambda xs, v: strs(xs) != v),
    ("eq", (["a", None], "a"), lambda xs, v: strs(xs) == v),
    ("ne", (["a", None], "a"), lambda xs, v: strs(xs) != v),
]


def row(name, args, f):
    got = f(*args).to_list()
    return "  (" + " ".join([name, *(datum(a) for a in args), datum(got)]) + ")"


def main():
    rows = [row(*v) for v in VALUES]
    text = (f";; Generated by scripts/nul-expected.py from Python polars {pl.__version__};"
            " do not edit.\n(\n" + "\n".join(rows) + ")\n")
    OUT.write_text(text)


if __name__ == "__main__":
    main()

"""Writes polars/scribblings/data/reductions-expected.rktd from Python polars.

Run from the repo root with Python polars 1.42.1:
    python3 -I scripts/reductions-expected.py
"""

import datetime as dt
import decimal
import pathlib

import polars as pl

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = ROOT / "polars" / "scribblings" / "data"
OPS = ["sum", "mean", "min", "max", "std", "var", "n_unique"]

CASES = [
    ("int8", pl.Int8, [100, None, 100, 100]),
    ("int16", pl.Int16, [20000, None, 20000]),
    ("int32", pl.Int32, [1, None, 3]),
    ("int64", pl.Int64, [1, None, 3]),
    ("uint8", pl.UInt8, [200, None, 100]),
    ("uint16", pl.UInt16, [40000, None, 40000]),
    ("uint32", pl.UInt32, [1, None, 3]),
    ("uint64", pl.UInt64, [1, None, 3]),
    ("float32", pl.Float32, [0.1, None, 0.2, 0.4]),
    ("float64", pl.Float64, [1.5, None, 3.5]),
    ("string", pl.String, ["b", None, "a"]),
    ("boolean", pl.Boolean, [True, None, False]),
    ("date", pl.Date, [dt.date(2020, 1, 2), None, dt.date(2020, 1, 1)]),
    ("datetime", pl.Datetime("us"), [dt.datetime(2020, 1, 2), None, dt.datetime(2020, 1, 1)]),
    ("time", pl.Time, [dt.time(1), None, dt.time(3)]),
    ("(duration microseconds)", pl.Duration("us"),
     [dt.timedelta(hours=1), None, dt.timedelta(hours=3)]),
    ("categorical", pl.Categorical, ["b", None, "a"]),
    ("null", pl.Null, [None, None, None]),
]

SINGLES = [
    ("std", "int64", pl.Int64, [5], 1),
    ("std", "int64", pl.Int64, [5], 0),
    ("std", "int64", pl.Int64, [5, 6], 2),
    ("var", "int64", pl.Int64, [5, 6], 2),
    ("var", "float64", pl.Float64, [5.0], 1),
    ("std", "boolean", pl.Boolean, [True], 1),
    ("std", "boolean", pl.Boolean, [True], 0),
    ("std", "boolean", pl.Boolean, [True, True, False], 1),
    ("var", "boolean", pl.Boolean, [True, True, False], 1),
    ("sum", "boolean", pl.Boolean, [True, True, False], None),
    ("mean", "boolean", pl.Boolean, [True, True, False], None),
]


def enc(v, categorical=False):
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "#t" if v else "#f"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        return repr(v)
    if isinstance(v, decimal.Decimal):
        return f'(decimal "{v}")'
    if isinstance(v, str):
        return f'(category "{v}")' if categorical else f'"{v}"'
    if isinstance(v, dt.datetime):
        return (f"(datetime {v.year} {v.month} {v.day} {v.hour} {v.minute} "
                f"{v.second} {v.microsecond * 1000})")
    if isinstance(v, dt.date):
        return f"(date {v.year} {v.month} {v.day})"
    if isinstance(v, dt.time):
        return f"(time {v.hour} {v.minute} {v.second} {v.microsecond * 1000})"
    if isinstance(v, dt.timedelta):
        return f"(duration-us {v // dt.timedelta(microseconds=1)})"
    raise TypeError(repr(v))


def outcome(f, categorical):
    try:
        return enc(f(), categorical)
    except Exception:
        return "error"


def reduce(s, op, ddof=None):
    method = getattr(s, op)
    return method() if ddof is None else method(ddof=ddof)


def table(series_of):
    lines = []
    for op in OPS:
        cells = [outcome(lambda: reduce(s, op), s.dtype == pl.Categorical)
                 for s in series_of]
        lines.append(f"    ({op.replace('_', '-')} {' '.join(cells)})")
    return lines


out = [";; Generated by scripts/reductions-expected.py from Python polars "
       f"{pl.__version__}; do not edit.",
       "((cases"]
for name, dtype, rows in CASES:
    partial = pl.Series("v", rows, dtype=dtype)
    nulls = pl.Series("v", [None, None], dtype=dtype)
    empty = pl.Series("v", [], dtype=dtype)
    out.append(f"  ({name} ({' '.join(enc(v) for v in rows)})")
    out.extend(table([empty, nulls, partial]))
    out[-1] += ")"
out[-1] += ")"
prices = pl.read_parquet(DATA / "produce.parquet")["price"]
out.append(" (decimal")
out.extend(table([prices.head(0), prices.filter(prices.is_null()), prices]))
out[-1] += ")"
out.append(" (singles")
for op, name, dtype, rows, ddof in SINGLES:
    s = pl.Series("v", rows, dtype=dtype)
    expected = outcome(lambda: reduce(s, op, ddof), False)
    ddof_text = "#f" if ddof is None else str(ddof)
    out.append(f"  ({op} {name} ({' '.join(enc(v) for v in rows)}) {ddof_text} {expected})")
out[-1] += "))"
(DATA / "reductions-expected.rktd").write_text("\n".join(out) + "\n")
